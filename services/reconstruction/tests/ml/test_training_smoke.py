SIZE = 64


def _scene(rng, mask_path: Path, img_path: Path):
    """A generated room picture: floor below, wall above, a furniture box; the mask says so (values = SEMANTIC_CLASSES)."""
    mask = np.zeros((SIZE, SIZE), dtype=np.uint8)
    mask[: SIZE // 2] = SEMANTIC_CLASSES.index("wall")
    mask[SIZE // 2:] = SEMANTIC_CLASSES.index("floor")
    x, y = rng.integers(5, 30, 2)
    mask[y:y + 20, x:x + 20] = SEMANTIC_CLASSES.index("furniture")
    mask[0:3, 0:3] = 255  # an unlabelled corner
    colours = np.array([[120, 90, 60], [200, 200, 190], [40, 60, 160], [0, 0, 0], [0, 0, 0], [0, 0, 0]], dtype=np.uint8)
    rgb = colours[np.minimum(mask, 5)] + rng.integers(0, 20, (SIZE, SIZE, 3), dtype=np.uint8)
    Image.fromarray(rgb).save(img_path)
    Image.fromarray(mask).save(mask_path)
    return (float(x), float(y), 20.0, 20.0)


@pytest.fixture
def dataset(tmp_path):
    root = tmp_path / "ds"
    (root / "images").mkdir(parents=True)
    (root / "masks").mkdir()
    rng = np.random.default_rng(0)
    images, anns = [], []
    for i, split in enumerate(["train"] * 4 + ["val"] * 2 + ["test"]):
        box = _scene(rng, root / "masks" / f"{i}.png", root / "images" / f"{i}.png")
        images.append(ImageRecord(image_id=str(i), relative_path=f"{i}.png", width=SIZE, height=SIZE, venue_id=None, split=split,
                                  group_id=str(i), content_sha256=sha256_file(root / "images" / f"{i}.png"), origin="public_dataset",
                                  license="generated test fixture", semantic_mask=f"{i}.png"))
        anns.append(Annotation(f"a{i}", str(i), "box", BoundingBox(*box),
                               Provenance(source="human", annotator="test generator", created_at="2026-10-11", review_status="approved")))
    manifest = DatasetManifest(name="smoke", version="0.0.1", created_at="2026-10-11", object_classes=("box",),
                               schema_version=SCHEMA_VERSION, source="generated by tests/ml", license="test fixture",
                               annotation_method="generated with the images", semantic_classes=SEMANTIC_CLASSES,
                               preprocessing={"generator": "tests/ml/test_training_smoke.py"})
    (root / "manifest.json").write_text(json.dumps(to_dict(manifest)), encoding="utf-8")
    write_images(root / "images.jsonl", images)
    write_annotations(root / "annotations.jsonl", anns)
    report = validate(root)
    assert report.ok, report.errors
    write_lock(root, report)
    return root


def _tiny_segformer(path: Path) -> Path:
    from transformers import SegformerConfig, SegformerForSemanticSegmentation, SegformerImageProcessor

    torch.manual_seed(0)
    cfg = SegformerConfig(num_encoder_blocks=2, depths=[1, 1], sr_ratios=[2, 1], hidden_sizes=[8, 16], patch_sizes=[7, 3],
                          strides=[4, 2], num_attention_heads=[1, 1], mlp_ratios=[2, 2], decoder_hidden_size=16, num_labels=3,
                          id2label={0: "a", 1: "b", 2: "c"}, label2id={"a": 0, "b": 1, "c": 2})
    SegformerForSemanticSegmentation(cfg).save_pretrained(path, safe_serialization=True)
    SegformerImageProcessor(size={"height": SIZE, "width": SIZE}).save_pretrained(path)
    return path


def _args(**kw):
    base = dict(base_revision="", epochs=2, max_steps=0, lr=1e-3, batch=2, image_size=SIZE, seed=0, accept_base_license=None,
                allow_cpu=True, allow_pickle=False, processor="")
    base.update(kw)
    return argparse.Namespace(**base)


def test_segmentation_harness_trains_writes_a_card_and_loads_as_a_canonical_fine_tuned_model(dataset, tmp_path):
    base = _tiny_segformer(tmp_path / "base")
    out = tmp_path / "out"
    card = segmentation.train(_args(dataset=dataset, base_model=str(base), out=out))
    assert card["training"]["smoke_test_only"] is True and card["dataset"]["splits_used"] == ["train", "val"]
    assert card["dataset"]["sha256"] == json.loads((dataset / "DATASET_LOCK.json").read_text())["sha256"]
    assert read_card(out)["label_set"] == list(BUCKETS)
    assert (out / "model.safetensors").is_file()
    from transformers import AutoModelForSemanticSegmentation

    model = AutoModelForSemanticSegmentation.from_pretrained(out, use_safetensors=True)
    mapping, method = class_mapping(model.config.id2label)
    assert method == "canonical" and list(mapping.values()) == list(BUCKETS)
    p = provenance(str(out), requested_revision=None, resolved_revision=None)
    assert p.fine_tuned is True and p.kind == "trained"
    # Same seed, same data: the same loss history (reproducibility on CPU).
    again = segmentation.train(_args(dataset=dataset, base_model=str(base), out=tmp_path / "out2"))
    assert again["metrics"]["val_history"] == card["metrics"]["val_history"]


def test_training_refuses_research_only_weights_without_acknowledgement(dataset):
    with pytest.raises(TrainingRefused, match="research"):
        prepare(dataset, base_model="nvidia/segformer-b0-finetuned-ade-512-512", accept_base_license=None, allow_cpu=True,
                need_masks=True)


def test_training_refuses_cpu_unless_it_is_a_smoke_test(dataset):
    if torch.cuda.is_available():
        pytest.skip("a CUDA device is present")
    with pytest.raises(TrainingRefused, match="CUDA"):
        prepare(dataset, base_model="any", accept_base_license=None, allow_cpu=False, need_masks=True)


def test_training_refuses_an_unlocked_or_changed_dataset(dataset):
    (dataset / "DATASET_LOCK.json").unlink()
    with pytest.raises(TrainingRefused, match="not locked"):
        prepare(dataset, base_model="any", accept_base_license=None, allow_cpu=True, need_masks=True)


def _tiny_grounding_dino(path: Path) -> Path:
    from transformers import BertConfig, GroundingDinoConfig, GroundingDinoForObjectDetection, SwinConfig

    torch.manual_seed(0)
    backbone = SwinConfig(embed_dim=8, depths=[1, 1, 1, 1], num_heads=[1, 1, 1, 1], window_size=4,
                          out_features=["stage2", "stage3", "stage4"])
    text = BertConfig(hidden_size=16, num_hidden_layers=1, num_attention_heads=1, intermediate_size=16)
    cfg = GroundingDinoConfig(backbone_config=backbone, text_config=text, d_model=32, encoder_layers=1, decoder_layers=1,
                              encoder_attention_heads=2, decoder_attention_heads=2, encoder_ffn_dim=32, decoder_ffn_dim=32,
                              num_queries=10, encoder_n_points=1, decoder_n_points=1, num_feature_levels=4)
    GroundingDinoForObjectDetection(cfg).save_pretrained(path, safe_serialization=True)
    return path


def _cached_gdino_processor() -> str | None:
    try:
        from huggingface_hub import snapshot_download

        return snapshot_download("IDEA-Research/grounding-dino-tiny", revision="a2bb814dd30d776dcf7e30523b00659f4f141c71",
                                 allow_patterns=["*.json", "*.txt"], local_files_only=True)
    except Exception:  # noqa: BLE001 - not cached: the test is skipped, nothing is downloaded
        return None


def test_detection_harness_trains_on_boxes_and_writes_a_card(dataset, tmp_path):
    processor = _cached_gdino_processor()
    if processor is None:
        pytest.skip("the grounding-dino-tiny processor files are not in the local Hugging Face cache")
    base = _tiny_grounding_dino(tmp_path / "gdino")
    out = tmp_path / "gdino-out"
    card = detection.train(_args(dataset=dataset, base_model=str(base), processor=processor, out=out, epochs=1, max_steps=2, lr=1e-4))
    assert card["training"]["prompt"] == "box." and card["label_set"] == ["box"]
    assert read_card(out)["task"] == "zero-shot-object-detection" and (out / "model.safetensors").is_file()
    from chaya_worker.grounding_dino import GroundingDinoDetector

    det = GroundingDinoDetector(str(out))
    assert det.fine_tuned is True and det.provenance.kind == "trained"
    rgb = np.asarray(Image.open(dataset / "images" / "0.png").convert("RGB"))
    assert isinstance(det.detect(rgb, "box."), list)  # the production post-processing runs on this transformers version


def test_production_post_processing_matches_this_transformers_version():
    import inspect

    from transformers import GroundingDinoProcessor

    params = inspect.signature(GroundingDinoProcessor.post_process_grounded_object_detection).parameters
    assert "threshold" in params or "box_threshold" in params
