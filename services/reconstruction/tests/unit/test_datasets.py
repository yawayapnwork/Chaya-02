def test_semantic_masks_are_checked(good):
    root, images, anns = good
    (root / "masks").mkdir()
    Image.fromarray(np.zeros((30, 40), dtype=np.uint8)).save(root / "masks" / "ok.png")
    Image.fromarray(np.full((30, 40), 9, dtype=np.uint8)).save(root / "masks" / "values.png")
    Image.fromarray(np.zeros((10, 10), dtype=np.uint8)).save(root / "masks" / "size.png")
    images = [_public(r.image_id, r.split, r.content_sha256, semantic_mask=m) for r, m in zip(images, ("ok.png", "values.png", "size.png"), strict=True)]
    _write(root, images, anns)
    errors = _errors(root)
    assert "image 'im0'" not in errors
    assert "mask values [9] are not semantic classes" in errors
    assert "mask is 10x10, image is 40x30" in errors


def test_class_imbalance_is_a_warning(good):
    root, images, anns = good
