# ---- privacy gate --------------------------------------------------------------------------------------------------------

def _privacy_run(tmp: Path, names, *, listed=None, policy="fail-closed"):
    frames = tmp / "frames"
    for i, n in enumerate(names):
        _img(frames / n, 100 + i)
    tar = tmp / "frames-anon.tar"
    with tarfile.open(tar, "w") as t:
        for n in names:
            t.add(frames / n, arcname=n)
    listed = names if listed is None else listed
    report = tmp / "privacy-report.json"
    report.write_text(json.dumps({"frames": len(listed), "policy": policy, "detectors": {"faces": "haar"},
                                  "per_frame": [{"frame": n, "masked_fraction": 0.01} for n in listed]}), encoding="utf-8")
    return tar, report


def test_captured_frames_enter_only_as_their_anonymised_bytes(tmp_path, good):
    root, images, anns = good
    tar, report = _privacy_run(tmp_path / "run", ["f1.png", "f2.png"])
    records = import_capture(root, tar, report, run_id="run-1", venue_id="v1", split="train", capture_id="cap-1")
    assert {r.group_id for r in records} == {"capture:cap-1"}
    p = records[0].privacy
    assert p["status"] == "ANONYMISED" and p["anonymised_frame_sha256"] == records[0].content_sha256
    _write(root, images + records, anns + [_ann(f"c{i}", r.image_id) for i, r in enumerate(records)])
    assert validate(root).ok, validate(root).errors


def test_a_captured_image_without_privacy_evidence_or_with_other_bytes_is_refused(good):
    root, images, anns = good
    raw = ImageRecord(image_id="raw", relative_path="im0.png", width=40, height=30, venue_id="v", split="train", group_id="g",
                      content_sha256=images[0].content_sha256, origin="capture")
    swapped = ImageRecord(image_id="swap", relative_path="im1.png", width=40, height=30, venue_id="v", split="val", group_id="g2",
                          content_sha256=images[1].content_sha256, origin="capture",
                          privacy={"status": "ANONYMISED", "frame_archive_kind": "FRAME_ARCHIVE_ANON", "policy": "fail-closed",
                                   "privacy_report_sha256": "r", "anonymised_frame_sha256": "0" * 64})
    _write(root, [raw, swapped], [_ann("a", "raw"), _ann("b", "swap")])
    errors = _errors(root)
    assert "a captured image needs privacy evidence" in errors
    assert "the stored image is not the anonymised frame" in errors


def test_the_privacy_gate_refuses_frames_the_report_does_not_vouch_for(tmp_path, good):
    root, _, _ = good
    tar, report = _privacy_run(tmp_path / "a", ["f1.png", "f2.png"], listed=["f1.png"])
    with pytest.raises(PrivacyGateError):
        import_capture(root, tar, report, run_id="r", venue_id="v", split="train")
    tar, report = _privacy_run(tmp_path / "b", ["f1.png"], policy="best-effort")
    with pytest.raises(PrivacyGateError):
        import_capture(root, tar, report, run_id="r", venue_id="v", split="train")
    with pytest.raises(PrivacyGateError):
        admissible_frames({"policy": "fail-closed", "frames": 3, "per_frame": [{"frame": "a"}]})


def test_split_assignment_is_per_group_and_reproducible():
    groups = [f"capture:{i}" for i in range(400)]
    first = [assign_split(g, seed="s") for g in groups]
    assert first == [assign_split(g, seed="s") for g in groups]
    share = {s: first.count(s) / len(first) for s in ("train", "val", "test")}
    assert 0.6 < share["train"] < 0.8 and 0.08 < share["val"] < 0.22
    with pytest.raises(ValueError):
        assign_split("g", seed="s", ratios=(0.5, 0.5, 0.5))


