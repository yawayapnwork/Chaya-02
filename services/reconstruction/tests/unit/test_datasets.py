def _img(path: Path, seed: int, size=(40, 30)) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(np.random.default_rng(seed).integers(0, 255, (size[1], size[0], 3), dtype=np.uint8)).save(path)
    return sha256_file(path)


def _manifest(**over) -> DatasetManifest:
    m = dict(name="t", version="1.0.0", created_at="2026-10-11", object_classes=("chair", "sofa"), schema_version=SCHEMA_VERSION,
             source="tests", license="test fixture", annotation_method="generated by the test", semantic_classes=SEMANTIC_CLASSES,
             preprocessing={"rule": "test"})
    m.update(over)
    return DatasetManifest(**m)


def _human(review="approved") -> Provenance:
    return Provenance(source="human", annotator="tester", created_at="2026-10-11", review_status=review)


def _public(image_id: str, split: str, sha: str, **over) -> ImageRecord:
    r = dict(image_id=image_id, relative_path=f"{image_id}.png", width=40, height=30, venue_id=None, split=split,
             group_id=image_id, content_sha256=sha, origin="public_dataset", license="CC BY 4.0")
    r.update(over)
    return ImageRecord(**r)


def _write(root: Path, images, annotations, manifest=None):
    (root / "manifest.json").write_text(json.dumps(to_dict(manifest or _manifest())), encoding="utf-8")
    write_images(root / "images.jsonl", images)
    write_annotations(root / "annotations.jsonl", annotations)


def _ann(aid: str, image_id: str, cls="chair", box=(1, 1, 10, 10), prov=None) -> Annotation:
    return Annotation(aid, image_id, cls, BoundingBox(*box), prov or _human())


