def test_every_coco_panoptic_category_has_a_bucket_decision():
    cats = json.loads((FIXTURES / "coco-panoptic-categories.json").read_text(encoding="utf-8"))["categories"]
    undecided = [c["name"] for c in cats if c["name"] not in COCO_PANOPTIC_TO_BUCKET and c["name"] not in IGNORED]
    assert undecided == []
    assert set(COCO_PANOPTIC_TO_BUCKET.values()) <= set(SEMANTIC_CLASSES)
    things = {c["name"] for c in cats if c["isthing"]}
    assert set(COCO_DETECTION_CLASSES) <= things


def test_panoptic_ids_become_bucket_values_and_unlabelled_is_ignored():
    cats = {1: "floor-wood", 2: "chair", 3: "tent"}
    png = np.zeros((2, 3, 3), dtype=np.uint8)
    png[0, 0] = [5, 0, 0]          # segment 5 -> floor
    png[0, 1] = [6, 1, 0]          # segment 262 -> chair (furniture)
    png[1, 0] = [7, 0, 0]          # segment 7 -> tent (ignored)
    out = panoptic_to_semantic(png, [{"id": 5, "category_id": 1}, {"id": 262, "category_id": 2}, {"id": 7, "category_id": 3}], cats)
    assert out.tolist() == [[0, 2, IGNORE_INDEX], [IGNORE_INDEX, IGNORE_INDEX, IGNORE_INDEX]]
    assert bucket_index("stairs") == SEMANTIC_CLASSES.index("stairs") and bucket_index("nonexistent") == IGNORE_INDEX


def test_the_selection_rule():
    cats = [{"id": 1, "name": "floor-wood"}, {"id": 2, "name": "wall-brick"}, {"id": 3, "name": "person"}, {"id": 4, "name": "chair"}]

    def img(i, lic):
        return {"id": i, "license": lic, "width": 10, "height": 10}

    def ann(i, segs):
        return {"image_id": i, "segments_info": [{"category_id": c, "area": a} for c, a in segs]}

    pan = {"categories": cats,
           "images": [img(3, 4), img(1, 4), img(2, 1), img(4, 7), img(5, 4)],
           "annotations": [ann(3, [(1, 10), (2, 10)]), ann(1, [(1, 10), (2, 10)]), ann(2, [(1, 10), (2, 10)]),
                           ann(4, [(1, 10), (2, 10), (3, 5)]), ann(5, [(1, 1), (2, 50)])]}
    # 2: non-commercial licence; 4: has a person; 5: floor covers 1% only
    assert [c["image"]["id"] for c in select_images(pan)] == [1, 3]
